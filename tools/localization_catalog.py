"""Development-only catalog extraction/verification; not a runtime dependency."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HAN = re.compile(r'[\u3400-\u9fff]')
TOKEN = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|(?:u8|L|u|U)?"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')

def decode(token):
    token = token[token.index('"')+1:-1]
    escapes = {'n':'\n', 'r':'\r', 't':'\t', '0':'\0', '\\':'\\', '"':'"', "'":"'"}
    return re.sub(r'\\(.)', lambda m: escapes.get(m[1], m[0]), token)

def literals(path):
    text = path.read_text(encoding='utf-8-sig')
    tokens = list(TOKEN.finditer(text))
    i = 0
    while i < len(tokens):
        token = tokens[i]
        if '"' not in token[0][:3] or token[0].startswith(('//','/*',"'")):
            i += 1
            continue
        end = token.end()
        value = decode(token[0])
        j = i + 1
        while j < len(tokens) and not text[end:tokens[j].start()].strip() and tokens[j][0].startswith(('"','L"')):
            value += decode(tokens[j][0]);end = tokens[j].end();j += 1
        if HAN.search(value):
            line = text.count('\n',0,token.start())+1
            context = text.splitlines()[line-1].strip()
            yield token.start(),end,value,token[0].startswith('L"'),line,context
        i = j

def sources():
    return sorted(p for p in (ROOT/'native/src').iterdir()
                  if p.suffix in ('.cpp','.h','.inc') and '_test' not in p.name and '_exercise' not in p.name
                  and p.name != 'localization_catalog.inc')

def semantic(path, context):
    return (path.name == 'animation_analysis.cpp' and 'anyWord(' in context
            or path.name == 'assets.cpp' and 'p.filename()) ==' in context
            or path.name == 'app.cpp' and ('"##language"' in context or '"Language / ' in context))

def generate(check=False):
    pack = json.loads((ROOT/'native/locales/en-US.json').read_text(encoding='utf-8'))
    entries = pack['translations']
    fmt = re.compile(r'%(?:%|[-+ #0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn])')
    rows = ['// Generated by tools/localization_catalog.py --generate. Do not edit.']
    def cpp(s):
        return json.dumps(s,ensure_ascii=False).replace('\\u0000','\\0')
    for key, value in entries.items():
        assert value and isinstance(value,str), key
        assert fmt.findall(key) == fmt.findall(value), f'Format mismatch: {key}'
        assert key.count('\0') == value.count('\0') and key.endswith('\0') == value.endswith('\0'), key
        assert key[key.index('##'):] == value[value.index('##'):] if '##' in key else '##' not in value, key
        rows.append(f'add({cpp(key)}, {len(key.encode("utf-8"))}, {cpp(value)}, {len(value.encode("utf-8"))});')
    output = ROOT/'native/src/localization_catalog.inc'
    result = '\n'.join(rows)+'\n'
    if check:
        assert output.read_text(encoding='utf-8') == result, 'Regenerate embedded catalog'
    else:
        output.write_text(result,encoding='utf-8')
    for path in sources():
        text = path.read_text(encoding='utf-8-sig')
        for start,end,key,wide,line,context in literals(path):
            if semantic(path,context):
                continue
            assert key in entries, f'Missing translation: {path.name}:{line}: {key}'
            assert text[max(0,start-9):start].endswith(('edm::tr(', 'edm::trw(')), f'Unwrapped: {path.name}:{line}'
    print(f'Checked {len(entries)} translations and all native source call sites')

def wrap():
    for path in sources():
        text = path.read_text(encoding='utf-8-sig')
        original = text
        for start,end,key,wide,line,context in reversed(list(literals(path))):
            if semantic(path,context) or text[max(0,start-9):start].endswith(('edm::tr(', 'edm::trw(')):
                continue
            text = text[:start] + ('edm::trw(' if wide else 'edm::tr(') + text[start:end] + ')' + text[end:]
        if text != original:
            path.write_text(text,encoding='utf-8')

def extract():
    catalog = {}
    for path in sources():
        for start,end,key,wide,line,context in literals(path):
            catalog.setdefault(key,[]).append({'file':str(path.relative_to(ROOT)).replace('\\','/'),'line':line,'context':context})
    output = ROOT/'validation/localization/catalog-source.json'
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(json.dumps(catalog,ensure_ascii=False,indent=2),encoding='utf-8')
    print(f'{len(catalog)} unique strings; {sum(map(len,catalog.values()))} occurrences; {output}')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--wrap', action='store_true')
    args = parser.parse_args()
    if args.wrap: wrap()
    elif args.generate or args.check: generate(args.check)
    else: extract()
